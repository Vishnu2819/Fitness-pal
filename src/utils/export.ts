import { PersonalDetails, GoalDetails, CalculationResults } from '../types/fitness';

export function buildSummaryText(
  personal: PersonalDetails,
  goals: GoalDetails,
  results: CalculationResults
): string {
  const goalLabels: Record<string, string> = {
    lose: 'Lose Weight',
    gain: 'Gain Weight / Muscle',
    recomp: 'Body Recomposition',
    maintain: 'Maintain Weight',
  };

  const activityLabels: Record<string, string> = {
    sedentary: 'Sedentary (little or no exercise)',
    light: 'Lightly Active (1–3 days/week)',
    moderate: 'Moderately Active (3–5 days/week)',
    very: 'Very Active (6–7 days/week)',
    extra: 'Extra Active (physical job or 2x training)',
  };

  const timeBlock =
    results.weeksToGoal != null && results.weeklyRateKg != null
      ? `
--- TIME ESTIMATE ---
Target Weight:    ${
          personal.unitSystem === 'metric'
            ? `${goals.targetWeightKg} kg`
            : `${goals.targetWeightLbs} lbs`
        }
Estimated Time:   ${results.weeksToGoal} weeks (~${Math.round(results.weeksToGoal / 4.3)} months)
Weekly Rate:      ${results.weeklyRateKg} kg/week
`
      : goals.goal === 'recomp'
      ? '\n--- NOTE ---\nBody recomposition typically takes 3–6 months of consistent effort.\n'
      : '';

  return `
FITNESS PAL — PERSONALIZED NUTRITION SUMMARY
Generated: ${new Date().toLocaleDateString()}
============================================

PERSONAL DETAILS
Name:     ${personal.name || 'N/A'}
Age:      ${personal.age} years
Gender:   ${personal.gender === 'male' ? 'Male' : 'Female'}
Weight:   ${personal.unitSystem === 'metric' ? `${personal.weightKg} kg` : `${personal.weightLbs} lbs`}
Height:   ${
    personal.unitSystem === 'metric'
      ? `${personal.heightCm} cm`
      : `${personal.heightFt}ft ${personal.heightIn}in`
  }

GOAL & ACTIVITY
Goal:              ${goalLabels[goals.goal] || goals.goal}
Activity Level:    ${activityLabels[goals.activityLevel] || goals.activityLevel}

--- RESULTS ---
BMR (Basal Metabolic Rate):    ${results.bmr} kcal/day
TDEE (Total Daily Energy):     ${results.tdee} kcal/day
Target Calories:               ${results.targetCalories} kcal/day

--- DAILY MACROS ---
Protein:  ${results.proteinG}g  (${results.proteinG * 4} kcal)
Fat:      ${results.fatG}g  (${results.fatG * 9} kcal)
Carbs:    ${results.carbsG}g  (${results.carbsG * 4} kcal)
${timeBlock}
============================================
Generated by Fitness Pal
  `.trim();
}

export function downloadSummary(text: string, filename = 'fitness-pal-summary.txt'): void {
  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const textarea = document.createElement('textarea');
    textarea.value = text;
    textarea.style.position = 'fixed';
    textarea.style.opacity = '0';
    document.body.appendChild(textarea);
    textarea.focus();
    textarea.select();
    const success = document.execCommand('copy');
    document.body.removeChild(textarea);
    return success;
  }
}
